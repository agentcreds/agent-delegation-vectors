#!/usr/bin/env python3
"""The vectors' release manifest: `RELEASE.json` and `SHA256SUMS`, generated never hand-edited.

The vectors are the standard. A release is a named, byte-exact set of them, pinned to the
revision of `draft-reece-wimse-cross-org-delegation` it was built against; anything that
claims to pass the vectors names the release, and anything that ships the vectors (the
reference SDK included) is checked against it. Releases are named

    draft-NN.M      NN = draft revision the vectors target (02 for -02)
                    M  = release of the vectors within that revision, from 0

NN moves only when the draft does. M moves whenever a vector file's bytes change - a fix,
a new case, a regeneration. A release name is never reused for different bytes and a tag
is never moved, so "we pass draft-02.0" means one thing forever.

    release.py --check                         verify the files match the manifest
    release.py --write --release draft-02.1    regenerate the manifest for changed bytes
    release.py --tag-matches <tag>             CI on a tag: the tag must be this release

`--write` refuses to keep the current release name when bytes changed, and refuses a
release whose NN disagrees with `--spec`. Nothing here is specific to any implementation;
`sha256sum -c SHA256SUMS` verifies the same bytes with no Python at all.
"""

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MANIFEST = HERE / "RELEASE.json"
SUMS = HERE / "SHA256SUMS"
# The files that ARE the standard, in manifest order. Anything else in the directory
# (README, runner, this script) is documentation or tooling and is not pinned.
VECTOR_FILES = ("vectors.json", "jcs_vectors.json", "a2a_vectors.json")

RELEASE_RE = re.compile(r"^draft-(\d{2})\.(\d+)$")
SPEC_RE = re.compile(r"^draft-reece-wimse-cross-org-delegation-(\d{2})$")
DATATRACKER = "https://datatracker.ietf.org/doc/draft-reece-wimse-cross-org-delegation/"


def describe(path: Path) -> dict:
    data = path.read_bytes()
    doc = json.loads(data)
    cases = doc.get("cases")
    return {
        "bytes": len(data),
        "sha256": hashlib.sha256(data).hexdigest(),
        "format": doc.get("format"),
        "cases": len(cases) if isinstance(cases, (list, dict)) else None,
    }


def current_files() -> dict:
    missing = [f for f in VECTOR_FILES if not (HERE / f).exists()]
    if missing:
        sys.exit(f"NO missing vector file(s): {', '.join(missing)}")
    return {f: describe(HERE / f) for f in VECTOR_FILES}


def load_manifest() -> dict | None:
    if not MANIFEST.exists():
        return None
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def render_sums(files: dict) -> str:
    # The exact `sha256sum` line format, so `sha256sum -c SHA256SUMS` works unmodified.
    return "".join(f"{v['sha256']}  {name}\n" for name, v in files.items())


def render_manifest(release: str, spec: str, files: dict) -> str:
    doc = {
        "release": release,
        "spec": spec,
        "spec_url": f"https://www.ietf.org/archive/id/{spec}.txt",
        "datatracker": DATATRACKER,
        "files": files,
        "note": (
            "Generated by release.py - do not edit. `release` names this exact set of bytes; "
            "verify with `sha256sum -c SHA256SUMS` or `python release.py --check`."
        ),
    }
    return json.dumps(doc, indent=2) + "\n"


def check() -> int:
    manifest = load_manifest()
    if manifest is None:
        print("NO RELEASE.json is missing - run release.py --write --release draft-NN.0")
        return 1
    errors = []
    release, spec = manifest.get("release", ""), manifest.get("spec", "")
    m_rel, m_spec = RELEASE_RE.match(release), SPEC_RE.match(spec)
    if not m_rel:
        errors.append(f"release {release!r} is not of the form draft-NN.M")
    if not m_spec:
        errors.append(f"spec {spec!r} is not a draft-reece-wimse-cross-org-delegation-NN")
    if m_rel and m_spec and m_rel.group(1) != m_spec.group(1):
        errors.append(f"release {release} targets draft revision {m_rel.group(1)} but spec is {spec}")

    listed = manifest.get("files", {})
    for name in VECTOR_FILES:
        if name not in listed:
            errors.append(f"{name} is not in the manifest")
    for name in listed:
        if name not in VECTOR_FILES:
            errors.append(f"{name} is listed but is not a vector file")

    actual = current_files()
    for name, want in listed.items():
        have = actual.get(name)
        if have is None:
            continue
        for key in ("bytes", "sha256", "format", "cases"):
            if want.get(key) != have[key]:
                errors.append(f"{name}: {key} is {have[key]!r}, manifest says {want.get(key)!r}")

    if not SUMS.exists():
        errors.append("SHA256SUMS is missing")
    elif SUMS.read_text(encoding="utf-8") != render_sums({n: listed[n] for n in VECTOR_FILES if n in listed}):
        errors.append("SHA256SUMS does not match RELEASE.json (regenerate with --write)")

    if errors:
        print("NO vectors do not match their release manifest:")
        for e in errors:
            print(f"  - {e}")
        print("  Changed bytes need a new release: release.py --write --release draft-NN.M")
        return 1
    print(f"ok {release} ({spec}): " + ", ".join(
        f"{n} {v['bytes']}B {v['sha256'][:12]}" for n, v in actual.items()))
    return 0


def write(release: str | None, spec: str | None) -> int:
    previous = load_manifest() or {}
    files = current_files()
    release = release or previous.get("release")
    spec = spec or previous.get("spec")
    if not release or not spec:
        sys.exit("NO first manifest needs both --release draft-NN.0 and --spec draft-reece-wimse-cross-org-delegation-NN")
    m_rel, m_spec = RELEASE_RE.match(release), SPEC_RE.match(spec)
    if not m_rel or not m_spec:
        sys.exit(f"NO bad names: release {release!r} must be draft-NN.M and spec {spec!r} a draft-reece-wimse-cross-org-delegation-NN")
    if m_rel.group(1) != m_spec.group(1):
        sys.exit(f"NO release {release} does not target the revision of {spec}")

    same_bytes = previous.get("files") == files
    if previous and not same_bytes and release == previous.get("release"):
        sys.exit(
            f"NO the vector bytes changed but the release is still {release}. A release name is "
            "never reused for different bytes: pass --release with the next number."
        )
    if previous and same_bytes and release != previous.get("release") and spec == previous.get("spec"):
        sys.exit(
            f"NO nothing changed since {previous['release']}; a new release needs new bytes "
            "or a new draft revision."
        )

    MANIFEST.write_text(render_manifest(release, spec, files), encoding="utf-8", newline="\n")
    SUMS.write_text(render_sums(files), encoding="utf-8", newline="\n")
    print(f"wrote {release} ({spec}) -> RELEASE.json, SHA256SUMS")
    return 0


def tag_matches(tag: str) -> int:
    manifest = load_manifest()
    release = (manifest or {}).get("release")
    if tag != release:
        print(f"NO tag {tag!r} does not name the manifest's release {release!r}: a tag must be "
              "cut from a commit whose RELEASE.json says the same thing.")
        return 1
    print(f"ok tag {tag} matches RELEASE.json")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--tag-matches", metavar="TAG")
    ap.add_argument("--release", help="draft-NN.M (with --write)")
    ap.add_argument("--spec", help="draft-reece-wimse-cross-org-delegation-NN (with --write)")
    a = ap.parse_args()
    if a.check:
        return check()
    if a.write:
        return write(a.release, a.spec)
    return tag_matches(a.tag_matches)


if __name__ == "__main__":
    sys.exit(main())
